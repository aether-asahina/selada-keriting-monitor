        generateGrowthCSV() {
            const headers = [
                'Image_ID',
                'Plant_ID',
                'Waktu_WIB',
                'HST_Day',
                'Lebar_Daun_px',
                'Lebar_Daun_mm',
                'Luas_Siluet_px2',
                'Luas_Siluet_mm2',
                'Kualitas_Status',
                'Proses_Status',
                'Camera_ID',
                'Algoritma'
            ];

            const lines = [headers.map(h => Sec.escapeCSV(h)).join(',')];

            this.records.forEach(r => {
                lines.push([
                    Sec.escapeCSV(r.image_id),
                    Sec.escapeCSV(r.plant_id),
                    Sec.escapeCSV(r.time_wib),
                    Sec.escapeCSV(r.hst_day),
                    Sec.escapeCSV(r.leaf_width_px),
                    Sec.escapeCSV(r.leaf_width_mm !== null ? r.leaf_width_mm : 'Belum_Kalibrasi'),
                    Sec.escapeCSV(r.leaf_area_px),
                    Sec.escapeCSV(r.leaf_area_mm2 !== null ? r.leaf_area_mm2 : 'Belum_Kalibrasi'),
                    Sec.escapeCSV(r.quality_status),
                    Sec.escapeCSV(r.processing_status),
                    Sec.escapeCSV(r.camera_id),
                    Sec.escapeCSV(r.algorithm_version)
                ].join(','));
            });

            return lines.join('\n');
        }

        downloadCSV() {
            const csv = this.generateGrowthCSV();
            const blob = new Blob([csv], { type: 'text/csv;charset=utf-8;' });
            const url = URL.createObjectURL(blob);
            const a = document.createElement('a');
            a.href = url;
            a.download = `pertumbuhan_daun_selada_${Date.now()}.csv`;
            document.body.appendChild(a);
            a.click();
            document.body.removeChild(a);
            URL.revokeObjectURL(url);
        }
